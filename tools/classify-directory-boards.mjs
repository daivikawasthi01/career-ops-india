#!/usr/bin/env node
/**
 * classify-directory-boards.mjs: turn the careers-directory list (data/careers-directory.tsv, from
 * import-careers-directory.mjs) into verified portals.yml entries WITHOUT an LLM. Each row whose URL host is an ATS
 * career-ops has a provider for is resolved through the real provider registry and fetched once; it becomes a board
 * entry only when it answers with at least one posting. The directory states the company, so the name is trusted
 * (confidence high). Rows already tracked in portals.yml are skipped; custom-site rows are left to discover-careers.
 *
 * Output (append-only, resumable): data/directory-boards.tsv (company, ats, url, provider, jobs, india_jobs, verdict, date)
 *                                  data/directory-boards.yml  (verified boards, to review and paste under tracked_companies)
 * Errors that look transient are retried next run; definite failures are remembered for 14 days.
 *
 *   node tools/classify-directory-boards.mjs [--limit N] [--workers 4] [--max-minutes 30] [--emit-only]
 */
import { readFileSync, existsSync, appendFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { loadProviders, resolveProvider } from '../providers/_registry.mjs';
import { makeHttpCtx } from '../providers/_http.mjs';
import { INDIA_RE } from './probe-india-ats.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = process.env.CAREER_OPS_ROOT || join(resolve(HERE, '..', '..'), 'career-ops');
const DATA = join(ROOT, 'data');
export const SCANNABLE = new Set(['keka', 'darwinbox', 'zoho-recruit', 'eightfold', 'greenhouse', 'lever', 'ashby', 'workday', 'smartrecruiters', 'workable', 'bamboohr', 'recruitee', 'breezy', 'icims', 'oracle', 'successfactors', 'freshteam']);
const TRANSIENT = /timeout|timed out|429|5\d\d|fetch failed|ECONN|ETIMEDOUT|EAI_AGAIN|abort/i;
const RETRY_AFTER_DAYS = 14;

export function boardsYaml(rows) {
  const out = ['# Generated by tools/classify-directory-boards.mjs. Each board answered with postings. Review, then paste under tracked_companies.', ''];
  for (const r of rows.filter((x) => x.verdict === 'ok' && Number(x.jobs) > 0)) out.push(`- name: ${JSON.stringify(r.company)}`, `  careers_url: ${r.url}`, `  notes: ${JSON.stringify(`${r.ats} board from the careersat.tech directory, ${r.jobs} jobs (${r.india} India)`)}`, '  enabled: true', '');
  return out.join('\n');
}
const lines = (f) => (existsSync(f) ? readFileSync(f, 'utf8').split('\n') : []);
const readLedger = (f) => lines(f).slice(1).filter(Boolean).map((l) => { const [company, ats, url, provider, jobs, india, verdict, date, detail] = l.split('\t'); return { company, ats, url, provider, jobs, india, verdict, date, detail }; });

async function main() {
  const argv = process.argv.slice(2);
  const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
  const ledgerFile = join(DATA, 'directory-boards.tsv'), yamlFile = join(DATA, 'directory-boards.yml');
  mkdirSync(DATA, { recursive: true });
  if (!existsSync(ledgerFile)) writeFileSync(ledgerFile, 'company\tats\turl\tprovider\tjobs\tindia_jobs\tverdict\tdate\tdetail\n');
  if (argv.includes('--emit-only')) { writeFileSync(yamlFile, boardsYaml(readLedger(ledgerFile))); return; }
  const dir = lines(join(DATA, 'careers-directory.tsv')).slice(1).filter(Boolean).map((l) => { const [company, url, ats, inPortals] = l.split('\t'); return { company, url, ats, inPortals }; });
  if (!dir.length) { console.error('classify-directory-boards: run import-careers-directory.mjs first'); process.exit(1); }
  const today = new Date().toISOString().slice(0, 10);
  const recent = new Map(); for (const r of readLedger(ledgerFile)) recent.set(r.url, r);
  const fresh = (r) => r && (r.verdict === 'ok' || (r.verdict === 'error' && (Date.parse(today) - Date.parse(r.date)) / 864e5 < RETRY_AFTER_DAYS));
  const todo = dir.filter((r) => SCANNABLE.has(r.ats) && r.inPortals !== 'yes' && !fresh(recent.get(r.url))).slice(0, Number(opt('--limit', 0)) || Infinity);
  const quiet = console.error; console.error = () => {};
  const providers = await loadProviders(join(HERE, '..', 'providers'));
  console.error = quiet;
  const ctx = makeHttpCtx(); ctx.maxPages = 1;
  const deadline = Date.now() + (Number(opt('--max-minutes', 0)) || 1e9) * 60000;
  let i = 0, ok = 0, bad = 0, skipped = 0;
  async function worker() {
    for (; Date.now() < deadline; ) {
      const r = todo[i++]; if (!r) return;
      const entry = { name: r.company, careers_url: r.url };
      const hit = resolveProvider(entry, providers);
      const prov = hit?.provider; let row;
      if (!prov) row = { verdict: 'no-provider', provider: '', jobs: 0, india: 0, detail: 'no provider claims this URL' };
      else {
        try { const jobs = await prov.fetch(entry, ctx); row = { verdict: jobs.length ? 'ok' : 'empty', provider: prov.id, jobs: jobs.length, india: jobs.filter((j) => INDIA_RE.test(j.location || '')).length, detail: '' }; }
        catch (e) { const msg = String(e?.message || e).slice(0, 100); if (TRANSIENT.test(msg)) { skipped++; continue; } row = { verdict: 'error', provider: prov.id, jobs: 0, india: 0, detail: msg }; }
      }
      row.verdict === 'ok' ? ok++ : bad++;
      appendFileSync(ledgerFile, [r.company, r.ats, r.url, row.provider, row.jobs, row.india, row.verdict, today, row.detail].map((v) => String(v).replace(/[\t\r\n]+/g, ' ')).join('\t') + '\n');
      await new Promise((s) => setTimeout(s, 150));
    }
  }
  await Promise.all(Array.from({ length: Number(opt('--workers', 4)) }, worker));
  const latest = new Map(); for (const r of readLedger(ledgerFile)) latest.set(r.url, r);
  writeFileSync(yamlFile, boardsYaml([...latest.values()]));
  console.log(`classify-directory-boards: ${todo.length} candidates, ${ok} verified boards, ${bad} empty/failed, ${skipped} transient (retry next run). See ${yamlFile}`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main().catch((e) => { console.error(e); process.exit(1); });
