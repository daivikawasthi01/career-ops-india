// The Company tab against a stubbed server (browser/e2e/company_server.py): research, people with sources, public contacts, mail checks and
// the saved answer on a second visit. Screenshots go to AF_SHOTS.
import { chromium } from 'playwright';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ext = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = process.env.AF_SHOTS || tmpdir();
const ctx = await chromium.launchPersistentContext(mkdtempSync(path.join(tmpdir(), 'af-profile-')), { channel: 'chromium', headless: true, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`] });
const results = [];
const check = (name, ok, extra = '') => { results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? '  ' + extra : ''}`); };
const sw = ctx.serviceWorkers()[0] || (await ctx.waitForEvent('serviceworker'));
const id = new URL(sw.url()).host;
const p = await ctx.newPage();
await p.setViewportSize({ width: 400, height: 900 });
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto(`chrome-extension://${id}/app/panel.html`);
await p.getByRole('tab', { name: 'Company' }).click();
check('tab explains itself before any search', /nothing is sent to anyone/i.test(await p.locator('#app').innerText()));
await p.screenshot({ path: path.join(out, 'company-empty.png') });
await p.getByLabel('Company', { exact: true }).fill('Acme');
await p.getByRole('button', { name: 'Research' }).click();
await p.waitForSelector('[data-person]', { timeout: 20000 });
const text = await p.locator('#app').innerText();
check('size band and headcount note shown', /Small company/.test(text) && /about 180 people/.test(text));
check('two people with source links', (await p.locator('[data-person]').count()) === 2 && (await p.locator('[data-person] a[href*="news.example"]').count()) === 1);
check('public email and phone shown with their page', /hello@acme\.com/.test(text) && /\+918012345678/.test(text));
await p.screenshot({ path: path.join(out, 'company-result.png'), fullPage: true });
const dom = await p.locator('[data-domains]').innerText();
check('work email domain found and offered ahead of the website domain', /acme-mail\.com/.test(dom) && /sam\.rivera@acme-mail\.com/.test(dom) && /first\.last/.test(dom), dom.replace(/\s+/g, ' ').slice(0, 140));
await p.locator('[data-person="Ada Lovelace"]').getByRole('button', { name: 'Find email' }).click();
await p.waitForSelector('[data-person="Ada Lovelace"] [data-mail]', { timeout: 20000 });
const mailText = await p.locator('[data-person="Ada Lovelace"]').innerText();
check('likely address first, ruled-out ones folded away', /Mailbox exists/.test(mailText) && /ruled out/.test(mailText) && !/Does not exist/.test(mailText), mailText.replace(/\s+/g, ' ').slice(0, 120));
await p.locator('[data-person="Ada Lovelace"]').getByRole('button', { name: /Bounce risk/ }).first().click();
check('risk detail says it is an estimate', /not a measured probability/.test(await p.locator('[data-person="Ada Lovelace"]').innerText()));
const box = p.locator('[data-person="Ada Lovelace"]');
await box.getByRole('button', { name: 'Draft email' }).click();
await box.getByRole('button', { name: 'Write the email' }).click();
await box.getByLabel('Email body').waitFor({ timeout: 20000 });
check('email written, to pre-filled with the checked address', /^Hi Ada,/.test(await box.getByLabel('Email body').inputValue()) && (await box.getByLabel('To').inputValue()) === 'ada.lovelace@acme-mail.com');
check('Gmail not connected yet: Connect offered, no draft button', (await box.getByRole('button', { name: 'Connect Gmail' }).count()) === 1 && (await box.getByRole('button', { name: 'Create Gmail draft' }).count()) === 0);
await p.screenshot({ path: path.join(out, 'company-outreach.png'), fullPage: true });
const kb = readFileSync('/tmp/af-company-server.log', 'utf8').match(/DB (\S+)/)[1].replace(/kb\.sqlite$/, '');
await box.getByRole('button', { name: 'Draft cover letter' }).click();
const texBox = box.getByLabel('Cover letter LaTeX');
await texBox.waitFor({ timeout: 20000 });
await box.locator('img[alt="Cover letter page 1"]').waitFor({ timeout: 60000 });
const tex0 = await texBox.inputValue();
check('cover letter drafted as tex for this job, addressed to the person, and compiled with a preview', /\\documentclass/.test(tex0) && /Dear Ada,/.test(tex0) && /Compiles/.test(await box.innerText()));
await texBox.fill(tex0.replace('Kubernetes operations', 'Kubernetes operations and on-call'));
check('editing the tex marks the preview stale', /Edited since the last preview/.test(await box.innerText()));
await box.getByRole('button', { name: 'Compile preview' }).click();
await box.locator('text=Compiles. This exact letter').waitFor({ timeout: 60000 });
await p.screenshot({ path: path.join(out, 'company-cover.png'), fullPage: true });
await box.getByRole('button', { name: 'Connect Gmail' }).click();      // opens the sign-in tab; the test then "signs in"
writeFileSync(kb + 'signed-in', '');
await box.getByRole('button', { name: 'Create Gmail draft' }).waitFor({ timeout: 20000 });
await box.getByRole('button', { name: 'Create Gmail draft' }).click();
await box.locator('[data-made]').waitFor({ timeout: 20000 });
const made = JSON.parse(readFileSync(kb + 'drafts.json', 'utf8'));
check('the reviewed tex was compiled into the attached letter', made.cover_has_edit === true);
check('draft made with CV and cover letter attached, nothing sent', made.to === 'ada.lovelace@acme-mail.com' && made.files.join() === 'Daivik-Awasthi-Resume.pdf,Cover-Letter-Acme.pdf', JSON.stringify(made));
check('result says nothing was sent and the contact was noted', /Nothing was sent/.test(await box.innerText()) && /Noted in your contacts/.test(await box.innerText()));
await p.screenshot({ path: path.join(out, 'company-drafted.png'), fullPage: true });
await p.getByRole('button', { name: /Check careers@/ }).click();
await p.waitForFunction(() => /Server accepts anything/.test(document.body.innerText), null, { timeout: 20000 });
check('generic address check shows catch-all', true);
await p.screenshot({ path: path.join(out, 'company-mail.png'), fullPage: true });
await p.reload();
await p.getByRole('tab', { name: 'Company' }).click();
await p.getByLabel('Company', { exact: true }).fill('Acme');
await p.waitForSelector('[data-person]', { timeout: 8000 });
check('second visit shows the saved answer without searching', (await p.locator('[data-person]').count()) === 2);
// A lookup keeps running when the tab is left: coming back joins it instead of starting again or losing it.
await p.getByLabel('Company', { exact: true }).fill('Slowly Ltd');
await p.getByRole('button', { name: 'Research' }).click();
await p.getByText('Looking up Slowly Ltd').waitFor();
await p.getByRole('tab', { name: 'Page' }).click();
await p.getByRole('tab', { name: 'Company' }).click();
await p.getByText(/Looking up Slowly Ltd/).waitFor({ timeout: 5000 });
await p.waitForSelector('[data-person]', { timeout: 30000 });
check('leaving the tab mid-lookup and coming back joins it and shows the answer', /Slowly Ltd/.test(await p.locator('#app').innerText()) || (await p.locator('[data-person]').count()) > 0);
check('no page errors', errors.length === 0, errors.join(' | ').slice(0, 200));
await ctx.close();
process.exit(results.every(Boolean) ? 0 : 1);
