// Needs the live server stopped (port 8765) or a copy of the extension on another port, and AF_PY (python) + AF_SERVE (a script that starts browser/e2e/server.py).
import { chromium } from 'playwright';
import { readFileSync, mkdtempSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const ext = path.resolve(here, '..');
const html = readFileSync(path.join(here, 'fixture.html'), 'utf8');
const URL = 'https://boards.greenhouse.io/acme/jobs/1';
const check = (n, ok, x = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}  ${x}`);
const ctx = await chromium.launchPersistentContext(mkdtempSync(path.join(tmpdir(), 'af-profile-')), { channel: 'chromium', headless: true, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`] });
const errs = []; ctx.on('weberror', (e) => errs.push(String(e.error())));
const page = await ctx.newPage();
await page.route(URL, (r) => r.fulfill({ contentType: 'text/html', body: html }));
await page.goto(URL);
await page.waitForTimeout(2500);
check('server down at load: nothing filled yet', (await page.$eval('#fn', (e) => e.value)) === '');
const srv = spawn(process.env.AF_PY, [process.env.AF_SERVE], { stdio: 'ignore' });   // the server comes up after the page loaded
let ok = false;
for (let i = 0; i < 40 && !ok; i++) { await page.waitForTimeout(1000); ok = (await page.$eval('#fn', (e) => e.value)) === 'Daivik'; }
check('page picks the form up after the server starts (init retry)', ok);
await page.waitForTimeout(1500);
const dockCount = await page.locator('.af-dock iframe').count();
check('in-page dock opens', dockCount === 1);
const src = await page.locator('.af-dock iframe').getAttribute('src').catch(() => '');
console.log('   dock src', src);
const f = page.frames().find((fr) => /panel\.html/.test(fr.url()));
await page.waitForTimeout(1500);
check('dock frame loads the panel (dynamic URL works)', !!f && (await f.title().catch(() => '')) === 'Apply', f ? f.url().slice(0, 60) : 'no frame');
check('data-af-theme set on page', ['dark', 'light'].includes(await page.evaluate(() => document.documentElement.getAttribute('data-af-theme'))));
const worker = ctx.serviceWorkers()[0] || (await ctx.waitForEvent('serviceworker'));
const id = new globalThis.URL(worker.url()).host;
const tabId = await worker.evaluate(async (u) => (await chrome.tabs.query({ url: u }))[0].id, URL);
const panel = await ctx.newPage();
await panel.setViewportSize({ width: 400, height: 900 });
await panel.goto(`chrome-extension://${id}/app/panel.html?tab=${tabId}`);
await panel.waitForTimeout(2000);
await panel.getByRole('radio', { name: 'Off' }).click();
await panel.waitForTimeout(1500);
check('Off removes the dock and chips from the page', (await page.locator('.af-dock').count()) === 0 && (await page.locator('.af-chip').count()) === 0);
check('Off: panel shows no fields', !/Ready/.test(await panel.locator('#app').innerText()));
await page.fill('#fn', '');
await panel.getByRole('radio', { name: 'Fill' }).click();
await panel.waitForTimeout(4000);
check('Fill after Off reads the page again and refills', (await page.$eval('#fn', (e) => e.value)) === 'Daivik');
check('no page errors', errs.length === 0, errs.join(' | ').slice(0, 200));
srv.kill(); await ctx.close();
