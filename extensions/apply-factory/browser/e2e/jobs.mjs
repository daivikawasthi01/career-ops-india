// The Jobs tab against the real jobs.db: list, search, a source filter, and opening a job in a new tab. Screenshots go to AF_SHOTS.
import { chromium } from 'playwright';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ext = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = process.env.AF_SHOTS || tmpdir();
const ctx = await chromium.launchPersistentContext(mkdtempSync(path.join(tmpdir(), 'af-profile-')), { channel: 'chromium', headless: true, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`] });
const results = [];
const check = (name, ok, extra = '') => { results.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? '  ' + extra : ''}`); };
const sw = ctx.serviceWorkers()[0] || (await ctx.waitForEvent('serviceworker'));
const id = new URL(sw.url()).host;
const p = await ctx.newPage();
await p.setViewportSize({ width: 400, height: 900 });
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto(`chrome-extension://${id}/app/panel.html`);
await p.getByRole('tab', { name: 'Jobs' }).click();
await p.waitForSelector('[data-job]', { timeout: 20000 });
const first = await p.locator('[data-job]').count();
check('jobs listed', first >= 20, `${first} rows`);
check('summary line shows totals', /\d+ (?:fit your level|jobs) of \d+/.test(await p.locator('#app').innerText()));
await p.screenshot({ path: path.join(out, 'jobs-list.png') });
await p.getByRole('button', { name: 'Filters' }).click();
await p.getByRole('button', { name: /^internshala/ }).click();
await p.keyboard.press('Escape');
await p.waitForFunction(() => { const r = [...document.querySelectorAll('[data-job]')]; return r.length > 0 && r.every((e) => /internshala/.test(e.innerText)); }, null, { timeout: 15000 }).catch(() => {});
const rows = await p.locator('[data-job]').allInnerTexts();
check('source filter keeps only internshala jobs', rows.length > 0 && rows.every((r) => /internshala/.test(r)), `${rows.length} rows`);
await p.screenshot({ path: path.join(out, 'jobs-filtered.png') });
await p.getByRole('button', { name: /Filters/ }).click();
await p.getByRole('button', { name: 'Clear filters' }).click();
await p.keyboard.press('Escape');
await p.getByLabel('Search jobs').fill('devops');
await p.waitForFunction(() => { const r = [...document.querySelectorAll('[data-job]')]; return r.length > 0 && r.every((e) => /devops/i.test(e.innerText)); }, null, { timeout: 15000 }).catch(() => {});
const hits = await p.locator('[data-job]').allInnerTexts();
check('search narrows the list', hits.length > 0 && hits.every((r) => /devops/i.test(r)), `${hits.length} rows`);
const newTab = ctx.waitForEvent('page');
await p.locator('[data-job]').first().getByRole('button', { name: 'Open' }).click();
const opened = await newTab;
check('Open puts the job in a new tab', /^https?:/.test(opened.url()) || opened.url() === 'about:blank', opened.url().slice(0, 70));
check('no page errors', errors.length === 0, errors.join(' | ').slice(0, 200));
await ctx.close();
process.exit(results.every(Boolean) ? 0 : 1);
